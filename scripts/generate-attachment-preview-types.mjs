#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(repoRoot, "server/internal/handler/attachment_preview_types.json");
const tsPath = resolve(repoRoot, "packages/views/editor/utils/attachment-preview-types.generated.ts");
const check = process.argv.includes("--check");
const data = JSON.parse(readFileSync(jsonPath, "utf8"));

const fields = ["text_extensions", "text_content_types", "text_basenames"];
for (const field of fields) {
  if (!Array.isArray(data[field]) || data[field].length === 0) {
    throw new Error(`attachment_preview_types.json: ${field} must be a non-empty array`);
  }
  const seen = new Set();
  for (const value of data[field]) {
    if (typeof value !== "string" || value.length === 0) {
      throw new Error(`attachment_preview_types.json: ${field} contains an invalid value`);
    }
    if (seen.has(value)) {
      throw new Error(`attachment_preview_types.json: ${field} contains duplicate ${value}`);
    }
    seen.add(value);
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/generate-attachment-preview-types.mjs.",
  "// Edit server/internal/handler/attachment_preview_types.json instead.",
  "",
];
for (const [field, exportName] of [
  ["text_extensions", "TEXT_PREVIEW_EXTENSIONS"],
  ["text_content_types", "TEXT_PREVIEW_CONTENT_TYPES"],
  ["text_basenames", "TEXT_PREVIEW_BASENAMES"],
]) {
  lines.push(`export const ${exportName}: ReadonlySet<string> = new Set([`);
  for (const value of data[field]) lines.push(`  ${JSON.stringify(value)},`);
  lines.push("]);", "");
}
const generated = `${lines.join("\n")}\n`;

if (check) {
  const current = readFileSync(tsPath, "utf8");
  if (current !== generated) {
    throw new Error("attachment preview generated TypeScript is stale");
  }
} else {
  writeFileSync(tsPath, generated);
}
