CREATE TABLE upstream_sync_config (
    singleton smallint NOT NULL DEFAULT 1 CHECK (singleton = 1),
    upstream_url text NOT NULL DEFAULT 'https://github.com/multica-ai/multica.git',
    upstream_branch text NOT NULL DEFAULT 'main',
    local_ref text NOT NULL DEFAULT 'origin/personal-studio-upstream',
    runtime_id uuid,
    agent_id uuid,
    autopilot_id uuid,
    batch_size integer NOT NULL DEFAULT 200 CHECK (batch_size BETWEEN 1 AND 500),
    sync_state text NOT NULL DEFAULT 'idle' CHECK (sync_state IN ('idle','bootstrap','incremental','paused')),
    bootstrap_base_sha text NOT NULL DEFAULT '',
    cursor_sha text NOT NULL DEFAULT '',
    head_sha text NOT NULL DEFAULT '',
    last_run_at timestamptz,
    error text NOT NULL DEFAULT '',
    created_by uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE upstream_sync_run (
    id uuid NOT NULL,
    mode text NOT NULL DEFAULT 'incremental' CHECK (mode IN ('bootstrap','incremental')),
    trigger_source text NOT NULL DEFAULT 'manual' CHECK (trigger_source IN ('manual','schedule','api','webhook')),
    task_id uuid,
    status text NOT NULL DEFAULT 'preparing' CHECK (status IN ('preparing','running','completed','failed','interrupted')),
    base_sha text NOT NULL DEFAULT '',
    observed_head_sha text NOT NULL DEFAULT '',
    limit_commits integer NOT NULL DEFAULT 200,
    cursor_sha text NOT NULL DEFAULT '',
    scanned_commits integer NOT NULL DEFAULT 0,
    absorbed_commits integer NOT NULL DEFAULT 0,
    item_count integer NOT NULL DEFAULT 0,
    has_more boolean NOT NULL DEFAULT true,
    result jsonb,
    error text NOT NULL DEFAULT '',
    lease_expires_at timestamptz,
    started_at timestamptz,
    completed_at timestamptz,
    created_by uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE upstream_sync_item (
    id uuid NOT NULL,
    run_id uuid NOT NULL,
    cluster_key text NOT NULL,
    title text NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    rationale text NOT NULL DEFAULT '',
    verdict text NOT NULL DEFAULT 'review' CHECK (verdict IN ('absorb','review','skip')),
    confidence text NOT NULL DEFAULT 'medium' CHECK (confidence IN ('high','medium','low')),
    presence text NOT NULL DEFAULT 'local' CHECK (presence IN ('local','partial','absent')),
    paths text[] NOT NULL DEFAULT '{}',
    commit_count integer NOT NULL DEFAULT 0,
    commit_shas text[] NOT NULL DEFAULT '{}',
    first_commit_at timestamptz,
    last_commit_at timestamptz,
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','adopted','ignored')),
    adopted_at timestamptz,
    adopted_by uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE upstream_sync_commit (
    commit_sha text NOT NULL,
    patch_id text NOT NULL DEFAULT '',
    item_id uuid,
    run_id uuid,
    absorbed boolean NOT NULL DEFAULT false,
    absorbed_method text NOT NULL DEFAULT '' CHECK (absorbed_method IN ('','patch_id','subject','ancestry')),
    subject text NOT NULL DEFAULT '',
    committed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
