package execenv

import (
	"fmt"
	"log/slog"
	"os"
	"regexp"
	"strings"
)

// 任务配置禁用 Codex 原生子代理；平台跟踪父线程，不能把未完成的子线程留在任务之外。
// 配置只写入任务级 CODEX_HOME，用户的全局配置由用户管理。
// 新建与恢复线程还会通过协议覆盖执行同一策略。

// 布局说明
//
// TOML 拒绝重定义一个已创建的表——包括经点号键隐式创建的。因此受管块必须适配用户
// 既有配置：
//
//   - 用户配置含顶层 `[features]` 表时，受管的 `multi_agent = false` 被注入「该表
//     内部」（带标记注释）。若在 TOML 根写 `features.multi_agent = false`，等于隐式
//     重定义同一张 `features` 表，Codex 用的严格 TOML 解析器（toml-rs）会以
//     `table 'features' already exists` 失败。
//   - 否则，受管块放在文件顶部，用点号键形式 `features.multi_agent = false`。

// multicaMultiAgentBeginMarker / multicaMultiAgentEndMarker 界定 multi-agent 专属的
// 受管块。与 sandbox 块分开标记，使两者可各自独立演进与迁移。
const (
	multicaMultiAgentBeginMarker = "# BEGIN multica-managed multi-agent (do not edit; regenerated by daemon)"
	multicaMultiAgentEndMarker   = "# END multica-managed multi-agent"
)

// 用 `\n*` 而非 `\n?`，使本块与 sandbox 受管块共存于同一文件时重跑不会累积空行。
// 同一正则在文件根（点号键形式）或 `[features]` 表内部都能匹配到块——只是块体键
// 不同。
var multiAgentBlockRe = regexp.MustCompile(
	`(?ms)^` + regexp.QuoteMeta(multicaMultiAgentBeginMarker) +
		`.*?^` + regexp.QuoteMeta(multicaMultiAgentEndMarker) + `\n*`)

var (
	// 匹配顶层 `[features]` 表头，容忍方括号内 TOML 可选空白与表头后的行内注释。
	rootFeaturesTableHeaderRe = regexp.MustCompile(`^\s*\[\s*features\s*\]\s*(?:#.*)?$`)
	// 匹配 `[features]` 表内（带可选空白的）`multi_agent = ...` 行。
	featuresTableMultiAgentRe = regexp.MustCompile(`^\s*multi_agent\s*=`)
	// 匹配 TOML 根的 `features.multi_agent = ...`（顶层点号键形式，含 TOML 点在两侧
	// 的可选空白）。
	rootDottedMultiAgentRe = regexp.MustCompile(`^\s*features\s*\.\s*multi_agent\s*=`)
)

// renderMulticaMultiAgentBlock 返回 daemon 管理的 multi-agent 块。注入 `[features]`
// 表内部时块体用 `multi_agent = false`，否则用 `features.multi_agent = false`。
func renderMulticaMultiAgentBlock(inFeaturesTable bool) string {
	var b strings.Builder
	b.WriteString(multicaMultiAgentBeginMarker)
	b.WriteString("\n")
	if inFeaturesTable {
		b.WriteString("multi_agent = false\n")
	} else {
		b.WriteString("features.multi_agent = false\n")
	}
	b.WriteString(multicaMultiAgentEndMarker)
	b.WriteString("\n")
	return b.String()
}

// stripUserMultiAgentDirectives 移除 TOML 根上任何 `features.multi_agent = ...` 行
// （点号键形式），外加任何落在顶层 `[features]` 表里的 `multi_agent = ...` 行。
// 两种形式编码同一个 TOML 键，会与受管块冲突。
//
// 其它表（`[features.experimental]`、`[profiles.foo]`……）原样保留：它们各在自己
// 作用域下，不在根上重定义 `features.multi_agent`。
func stripUserMultiAgentDirectives(content string) string {
	lines := strings.Split(content, "\n")
	out := make([]string, 0, len(lines))
	currentTable := "" // 空 = TOML 根
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if rootFeaturesTableHeaderRe.MatchString(line) {
			currentTable = "[features]"
			out = append(out, line)
			continue
		}
		if strings.HasPrefix(trimmed, "[") {
			currentTable = trimmed
			out = append(out, line)
			continue
		}
		switch currentTable {
		case "":
			if rootDottedMultiAgentRe.MatchString(trimmed) {
				continue
			}
		case "[features]":
			if featuresTableMultiAgentRe.MatchString(trimmed) {
				continue
			}
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

// hasRootFeaturesTable 报告文件是否含顶层 `[features]` 表头。`[features.experimental]`
// 这类子表不算：它们会隐式创建 `features`，但不会与根级 `features.multi_agent` 点号
// 键冲突。
func hasRootFeaturesTable(content string) bool {
	for _, line := range strings.Split(content, "\n") {
		if rootFeaturesTableHeaderRe.MatchString(line) {
			return true
		}
	}
	return false
}

// injectManagedBlockIntoFeaturesTable 把「表内形式」的受管块插到首个 `[features]`
// 表头行之后。调用方必须先剥掉任何旧受管块与表内任何用户设置的 `multi_agent`
// 指令。
func injectManagedBlockIntoFeaturesTable(content string) string {
	block := renderMulticaMultiAgentBlock(true)
	// 去掉结尾 `\n`，把块行拼接进既有行之间时不会多出孤立空行。
	blockLines := strings.Split(strings.TrimRight(block, "\n"), "\n")
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		if !rootFeaturesTableHeaderRe.MatchString(line) {
			continue
		}
		out := make([]string, 0, len(lines)+len(blockLines))
		out = append(out, lines[:i+1]...)
		out = append(out, blockLines...)
		out = append(out, lines[i+1:]...)
		return strings.Join(out, "\n")
	}
	return content
}

// ensureCodexMultiAgentConfig 把 daemon 管理的 multi-agent 块写进 per-task
// config.toml，使 Codex 原生子 agent 保持禁用。幂等：连跑两次产出同一文件。
func ensureCodexMultiAgentConfig(configPath string, logger *slog.Logger) error {
	data, err := os.ReadFile(configPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read config.toml: %w", err)
	}
	existing := string(data)

	// 总是先剥掉任何先前写下的受管块（根或表内形式），让重跑与布局切换保持干净。
	existing = multiAgentBlockRe.ReplaceAllString(existing, "")
	// 再剥掉用户指令的两种编码；受管块稍后重新加上规范形式。
	existing = stripUserMultiAgentDirectives(existing)

	var updated string
	if hasRootFeaturesTable(existing) {
		updated = injectManagedBlockIntoFeaturesTable(existing)
	} else {
		existing = strings.TrimLeft(existing, "\n")
		block := renderMulticaMultiAgentBlock(false)
		if existing == "" {
			updated = block
		} else {
			updated = block + "\n" + existing
		}
	}

	if updated == string(data) {
		return nil
	}

	if err := os.WriteFile(configPath, []byte(updated), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}
